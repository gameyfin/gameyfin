package org.gameyfin.app.core.plugins.marketplace

import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.ValueSource
import java.net.URI
import java.time.Instant
import java.util.*
import kotlin.test.assertEquals
import kotlin.test.assertFails
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

class MarketplaceIndexParserTest {

    private val indexUrl = URI("https://example.com/market/plugins.json")
    private val repositoryId = "test-market"
    private val sha = "a".repeat(64) + "B".repeat(64)

    private fun parse(json: String, url: URI = indexUrl) = MarketplaceIndexParser.parse(json, url, repositoryId)

    private fun release(
        version: String = "1.0.0",
        url: String = "https://example.com/files/plugin-1.0.0.jar",
        extra: String = ""
    ) = """{"version":"$version","url":"$url"${if (extra.isNotEmpty()) ",$extra" else ""}}"""

    private fun plugin(id: String, releases: String = release(), extra: String = "") =
        """{"id":"$id","releases":[$releases]${if (extra.isNotEmpty()) ",$extra" else ""}}"""

    private fun GameyfinPluginInfo.singleRelease(): GameyfinPluginRelease = gameyfinReleases.single()

    // --- Root format ---

    @Test
    fun `parses object root with plugins array`() {
        val result = parse("""{"plugins":[${plugin("a")},${plugin("b")}]}""")
        assertEquals(listOf("a", "b"), result.keys.toList())
    }

    @Test
    fun `parses plain array root`() {
        val result = parse("[${plugin("a")},${plugin("b")}]")
        assertEquals(listOf("a", "b"), result.keys.toList())
    }

    @Test
    fun `ignores unknown properties in object root and entries`() {
        val json = """{"version":2,"name":"Market","plugins":[{"id":"a","foo":"bar","releases":[{"version":"1","url":"a.jar","bar":1}]}]}"""
        assertEquals(setOf("a"), parse(json).keys)
    }

    @Test
    fun `empty plugins array yields empty result`() {
        assertTrue(parse("""{"plugins":[]}""").isEmpty())
        assertTrue(parse("[]").isEmpty())
    }

    @ParameterizedTest
    @ValueSource(strings = ["{}", """{"plugins":{}}""", """{"plugins":"x"}""", "\"text\"", "42", "null"])
    fun `invalid root is rejected`(json: String) {
        assertFailsWith<IllegalArgumentException> { parse(json) }
    }

    @Test
    fun `malformed JSON is rejected`() {
        assertFails { parse("{\"plugins\": [") }
    }

    @Test
    fun `malformed plugin entries are skipped without failing the whole index`() {
        val json = """{"plugins":[
            42,
            "text",
            {"id":"bad-releases","releases":"oops"},
            {"id":"bad-tags","tags":"x","releases":[${release()}]},
            ${plugin("good")}
        ]}"""
        assertEquals(listOf("good"), parse(json).keys.toList())
    }

    @Test
    fun `parses index generated by the marketplace scaffold`() {
        val json = javaClass.getResource("/marketplace/scaffold-plugins.json")!!.readText()
        val info = parse(json, URI("https://raw.githubusercontent.com/gameyfin/plugin-marketplace/HEAD/plugins.json"))
            .getValue("com.example.gameyfin.awesome-metadata")

        assertEquals("Awesome Metadata", info.name)
        assertEquals("Jane Doe", info.provider)
        assertEquals("MIT", info.license)
        assertEquals(listOf("GameMetadataProvider"), info.types)
        assertEquals(listOf("metadata", "covers"), info.tags)
        assertEquals(
            "https://raw.githubusercontent.com/janedoe/gameyfin-awesome-metadata/main/logo.png",
            info.logoUrl
        )
        assertEquals(listOf("1.1.0", "1.0.0"), info.gameyfinReleases.map { it.version })
        info.gameyfinReleases.forEach {
            assertEquals(">=2.5.1", it.requires)
            assertTrue(it.sha512sum!!.matches(Regex("^[0-9a-f]{128}$")))
        }
        assertEquals(Date.from(Instant.parse("2025-06-01T00:00:00Z")), info.gameyfinReleases[0].date)
    }

    @Test
    fun `preserves order of plugins`() {
        val result = parse("[${plugin("z")},${plugin("a")},${plugin("m")}]")
        assertEquals(listOf("z", "a", "m"), result.keys.toList())
    }

    // --- Field mapping ---

    @Test
    fun `maps all plugin and release fields`() {
        val json = """
            {"plugins":[{
              "id":"igdb",
              "name":"IGDB",
              "description":"Long description",
              "shortDescription":"Short",
              "provider":"Gameyfin",
              "license":"AGPL-3.0",
              "projectUrl":"https://github.com/gameyfin/igdb",
              "logo":"https://cdn.example.com/igdb.png",
              "types":["GameMetadataProvider","Other"],
              "tags":["metadata","official"],
              "releases":[{
                "version":"1.2.3",
                "date":"2024-05-01",
                "requires":">=2.0.0",
                "url":"https://example.com/files/igdb-1.2.3.jar",
                "sha512sum":"$sha",
                "changelog":"# Changes\n- Fix"
              }]
            }]}
        """.trimIndent()

        val info = parse(json).getValue("igdb")
        assertEquals("igdb", info.id)
        assertEquals("IGDB", info.name)
        assertEquals("Long description", info.description)
        assertEquals("Short", info.shortDescription)
        assertEquals("Gameyfin", info.provider)
        assertEquals("AGPL-3.0", info.license)
        assertEquals("https://github.com/gameyfin/igdb", info.projectUrl)
        assertEquals("https://cdn.example.com/igdb.png", info.logoUrl)
        assertEquals(listOf("GameMetadataProvider", "Other"), info.types)
        assertEquals(listOf("metadata", "official"), info.tags)
        assertEquals(repositoryId, info.repositoryId)

        val release = info.singleRelease()
        assertEquals("1.2.3", release.version)
        assertEquals(Date.from(Instant.parse("2024-05-01T00:00:00Z")), release.date)
        assertEquals(">=2.0.0", release.requires)
        assertEquals("https://example.com/files/igdb-1.2.3.jar", release.url)
        assertEquals(sha, release.sha512sum)
        assertEquals("# Changes\n- Fix", release.changelog)
        assertEquals(1, info.releases.size)
    }

    @Test
    fun `optional fields default to sensible values`() {
        val info = parse("[${plugin("minimal")}]").getValue("minimal")
        assertEquals("minimal", info.name)
        assertEquals("", info.description)
        assertNull(info.shortDescription)
        assertNull(info.provider)
        assertNull(info.license)
        assertNull(info.projectUrl)
        assertNull(info.logoUrl)
        assertEquals(emptyList(), info.types)
        assertEquals(emptyList(), info.tags)

        val release = info.singleRelease()
        assertEquals("*", release.requires)
        assertEquals(Date(0), release.date)
        assertNull(release.sha512sum)
        assertNull(release.changelog)
    }

    @Test
    fun `blank name falls back to id`() {
        val info = parse("[${plugin("my-plugin", extra = "\"name\":\"   \"")}]").getValue("my-plugin")
        assertEquals("my-plugin", info.name)
    }

    @Test
    fun `blank requires defaults to wildcard`() {
        val info = parse("[${plugin("a", release(extra = "\"requires\":\"  \""))}]").getValue("a")
        assertEquals("*", info.singleRelease().requires)
    }

    @Test
    fun `requires is trimmed`() {
        val info = parse("[${plugin("a", release(extra = "\"requires\":\" >=2.1.0 \""))}]").getValue("a")
        assertEquals(">=2.1.0", info.singleRelease().requires)
    }

    @Test
    fun `id and version are trimmed`() {
        val result = parse("[${plugin("  spaced  ", release(version = " 2.0.0 "))}]")
        val info = result.getValue("spaced")
        assertEquals("spaced", info.id)
        assertEquals("2.0.0", info.singleRelease().version)
    }

    @Test
    fun `keeps multiple releases in order`() {
        val releases = listOf(release("1.0.0", "a-1.jar"), release("2.0.0", "a-2.jar")).joinToString(",")
        val info = parse("[${plugin("a", releases)}]").getValue("a")
        assertEquals(listOf("1.0.0", "2.0.0"), info.gameyfinReleases.map { it.version })
        assertTrue(info.releases.all { it is GameyfinPluginRelease })
    }

    // --- Skipping invalid entries ---

    @Test
    fun `skips plugins without id`() {
        val json = """[{"name":"No ID","releases":[${release()}]},${plugin("   ")},${plugin("valid")}]"""
        assertEquals(setOf("valid"), parse(json).keys)
    }

    @Test
    fun `skips duplicate plugins and keeps the first one`() {
        val json = "[${plugin("a", release("1.0.0"))},${plugin("a", release("9.9.9"))}]"
        val result = parse(json)
        assertEquals(1, result.size)
        assertEquals("1.0.0", result.getValue("a").singleRelease().version)
    }

    @Test
    fun `skips plugins without releases`() {
        val json = """[{"id":"none"},{"id":"empty","releases":[]},${plugin("valid")}]"""
        assertEquals(setOf("valid"), parse(json).keys)
    }

    @Test
    fun `skips releases without version or url`() {
        val releases = listOf(
            """{"url":"no-version.jar"}""",
            """{"version":"  ","url":"blank-version.jar"}""",
            """{"version":"1.0.0"}""",
            """{"version":"1.0.1","url":"   "}""",
            release("2.0.0", "valid.jar")
        ).joinToString(",")
        val info = parse("[${plugin("a", releases)}]").getValue("a")
        assertEquals(listOf("2.0.0"), info.gameyfinReleases.map { it.version })
    }

    @Test
    fun `skips releases with invalid url`() {
        val releases = listOf(release("1.0.0", "ht tp://bad url"), release("2.0.0", "valid.jar")).joinToString(",")
        val info = parse("[${plugin("a", releases)}]").getValue("a")
        assertEquals(listOf("2.0.0"), info.gameyfinReleases.map { it.version })
    }

    @Test
    fun `skips plugins without any valid release`() {
        val json = "[${plugin("broken", """{"version":"1.0.0"}""")},${plugin("valid")}]"
        assertEquals(setOf("valid"), parse(json).keys)
    }

    // --- URL resolution ---

    @Test
    fun `resolves relative release url against index url`() {
        val info = parse("[${plugin("a", release(url = "files/a-1.0.0.jar"))}]").getValue("a")
        assertEquals("https://example.com/market/files/a-1.0.0.jar", info.singleRelease().url)
    }

    @Test
    fun `resolves root relative release url against index url`() {
        val info = parse("[${plugin("a", release(url = "/downloads/a.jar"))}]").getValue("a")
        assertEquals("https://example.com/downloads/a.jar", info.singleRelease().url)
    }

    @Test
    fun `resolves parent relative release url against index url`() {
        val info = parse("[${plugin("a", release(url = "../a.jar"))}]").getValue("a")
        assertEquals("https://example.com/a.jar", info.singleRelease().url)
    }

    @Test
    fun `keeps absolute release url`() {
        val info = parse("[${plugin("a", release(url = "https://cdn.example.org/a.jar"))}]").getValue("a")
        assertEquals("https://cdn.example.org/a.jar", info.singleRelease().url)
    }

    @Test
    fun `resolves relative logo url against index url`() {
        val info = parse("[${plugin("a", extra = "\"logo\":\"logos/a.png\"")}]").getValue("a")
        assertEquals("https://example.com/market/logos/a.png", info.logoUrl)
    }

    @Test
    fun `invalid logo url results in no logo`() {
        val info = parse("[${plugin("a", extra = "\"logo\":\"ht tp://bad logo\"")}]").getValue("a")
        assertNull(info.logoUrl)
    }

    @Test
    fun `project url is not resolved`() {
        val info = parse("[${plugin("a", extra = "\"projectUrl\":\"relative/project\"")}]").getValue("a")
        assertEquals("relative/project", info.projectUrl)
    }

    // --- SHA-512 ---

    @Test
    fun `keeps literal sha512 checksum`() {
        val info = parse("[${plugin("a", release(extra = "\"sha512sum\":\" $sha \""))}]").getValue("a")
        assertEquals(sha, info.singleRelease().sha512sum)
    }

    @Test
    fun `sha512 shorthand is resolved next to the plugin file`() {
        val info = parse("[${plugin("a", release(url = "files/a-1.0.0.jar", extra = "\"sha512sum\":\".sha512\""))}]")
            .getValue("a")
        assertEquals("https://example.com/market/files/a-1.0.0.sha512", info.singleRelease().sha512sum)
    }

    @Test
    fun `sha512 shorthand is case insensitive`() {
        val info = parse("[${plugin("a", release(url = "https://cdn.example.org/a.jar", extra = "\"sha512sum\":\".SHA512\""))}]")
            .getValue("a")
        assertEquals("https://cdn.example.org/a.sha512", info.singleRelease().sha512sum)
    }

    @Test
    fun `sha512 shorthand appends extension if the plugin file has none`() {
        val info = parse("[${plugin("a", release(url = "https://cdn.example.org/download/plugin", extra = "\"sha512sum\":\".sha512\""))}]")
            .getValue("a")
        assertEquals("https://cdn.example.org/download/plugin.sha512", info.singleRelease().sha512sum)
    }

    @Test
    fun `sha512 shorthand only replaces the extension of the file name and keeps the query`() {
        val info = parse("[${plugin("a", release(url = "https://cdn.v1.example.org/a.jar?raw=true", extra = "\"sha512sum\":\".sha512\""))}]")
            .getValue("a")
        assertEquals("https://cdn.v1.example.org/a.sha512?raw=true", info.singleRelease().sha512sum)
    }

    @Test
    fun `relative sha512 checksum url is resolved against index url`() {
        val info = parse("[${plugin("a", release(extra = "\"sha512sum\":\"checksums/a.sha512\""))}]").getValue("a")
        assertEquals("https://example.com/market/checksums/a.sha512", info.singleRelease().sha512sum)
    }

    @Test
    fun `absolute sha512 checksum url is kept`() {
        val info = parse("[${plugin("a", release(extra = "\"sha512sum\":\"https://cdn.example.org/a.jar.sha512\""))}]")
            .getValue("a")
        assertEquals("https://cdn.example.org/a.jar.sha512", info.singleRelease().sha512sum)
    }

    @Test
    fun `hex string of wrong length is treated as relative url`() {
        val info = parse("[${plugin("a", release(extra = "\"sha512sum\":\"abcdef\""))}]").getValue("a")
        assertEquals("https://example.com/market/abcdef", info.singleRelease().sha512sum)
    }

    @Test
    fun `unresolvable sha512 value is kept as is`() {
        val info = parse("[${plugin("a", release(extra = "\"sha512sum\":\"not a url\""))}]").getValue("a")
        assertEquals("not a url", info.singleRelease().sha512sum)
    }

    @Test
    fun `relative urls are resolved against file index urls`() {
        val info = parse(
            "[${plugin("a", release(url = "a.jar", extra = "\"sha512sum\":\".sha512\""), "\"logo\":\"a.png\"")}]",
            URI("file:///opt/market/plugins.json")
        ).getValue("a")
        assertEquals("file:/opt/market/a.jar", info.singleRelease().url)
        assertEquals("file:/opt/market/a.sha512", info.singleRelease().sha512sum)
        assertEquals("file:/opt/market/a.png", info.logoUrl)
    }

    // --- Dates ---

    @Test
    fun `parseDate parses ISO local dates as UTC start of day`() {
        assertEquals(Date.from(Instant.parse("2024-05-01T00:00:00Z")), MarketplaceIndexParser.parseDate("2024-05-01"))
    }

    @Test
    fun `parseDate parses offset date times`() {
        assertEquals(
            Date.from(Instant.parse("2024-05-01T08:15:30Z")),
            MarketplaceIndexParser.parseDate("2024-05-01T10:15:30+02:00")
        )
    }

    @Test
    fun `parseDate parses instants`() {
        assertEquals(
            Date.from(Instant.parse("2024-05-01T10:15:30.123Z")),
            MarketplaceIndexParser.parseDate("2024-05-01T10:15:30.123Z")
        )
    }

    @Test
    fun `parseDate trims input`() {
        assertEquals(Date.from(Instant.parse("2024-05-01T00:00:00Z")), MarketplaceIndexParser.parseDate("  2024-05-01 "))
    }

    @ParameterizedTest
    @ValueSource(strings = ["", "   ", "garbage", "01.05.2024", "2024-13-45", "2024-05-01T10:15:30"])
    fun `parseDate falls back to epoch for invalid dates`(value: String) {
        assertEquals(Date(0), MarketplaceIndexParser.parseDate(value))
    }

    @Test
    fun `parseDate falls back to epoch for null`() {
        assertEquals(Date(0), MarketplaceIndexParser.parseDate(null))
    }

    @Test
    fun `release with invalid date is kept with epoch date`() {
        val info = parse("[${plugin("a", release(extra = "\"date\":\"yesterday\""))}]").getValue("a")
        assertEquals(Date(0), info.singleRelease().date)
    }
}
